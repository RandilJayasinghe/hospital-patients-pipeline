"""
Builds the consolidated daily patient risk report -- the "final deliverable
of the running system" the assignment brief asks for: a report that answers
the business question by joining vitals trends with the latest lab results.

Produces two files per sim_day under data/reports/:
  daily_risk_report_{sim_day}.html  -- human-readable report with a ward
      risk-distribution chart and a per-patient table (reason codes, delta
      vs. yesterday), for screenshotting into the project report.
  daily_risk_report_{sim_day}.csv   -- the same per-patient rows, plain CSV,
      for anyone who wants to load it into a spreadsheet.

Invoked by Airflow's build_report task after run_batch_job succeeds.
"""

