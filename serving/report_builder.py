def fetch_report_data(dsn: str, sim_day: str) -> tuple[list[dict], list[dict], list[dict]]:
    with psycopg2.connect(dsn) as conn:
        with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
            cur.execute(
                """
                SELECT rd.patient_id, p.name, p.ward, p.bed,
                       rd.vitals_score, rd.vitals_band, rd.abnormal_test_count,
                       rd.adjusted_risk_score, rd.risk_band, rd.reason_codes,
                       rd.score_delta, rd.delta_direction,
                       (SELECT string_agg(l.test_type || ' ' || l.flag, ', ' ORDER BY l.test_type)
                          FROM batch.patient_lab_results l
                         WHERE l.patient_id = rd.patient_id AND l.sim_day = rd.sim_day
                           AND l.flag IN ('low', 'high')) AS abnormal_labs
                FROM batch.patient_risk_daily rd
                LEFT JOIN reference.patients p ON p.patient_id = rd.patient_id
                WHERE rd.sim_day = %s
                ORDER BY rd.adjusted_risk_score DESC
                """,
                (sim_day,),
            )
            rows = [dict(r) for r in cur.fetchall()]

            cur.execute(
                """
                SELECT patient_id, raised_at, score, risk_band
                FROM speed.clinical_alerts
                WHERE raised_at >= now() - interval '24 hours'
                ORDER BY raised_at DESC
                LIMIT 50
                """
            )
            alerts = [dict(r) for r in cur.fetchall()]

            cur.execute(
                """
                SELECT patient_id, raised_at, rule, observed_value, op, threshold
                FROM speed.vitals_alerts
                WHERE raised_at >= now() - interval '24 hours'
                ORDER BY raised_at DESC
                LIMIT 50
                """
            )
            spikes = [dict(r) for r in cur.fetchall()]

    return rows, alerts, spikes


def build_ward_chart(rows: list[dict]) -> str:
    band_counts = {"low": 0, "medium": 0, "high": 0}
    for r in rows:
        band_counts[r["risk_band"]] = band_counts.get(r["risk_band"], 0) + 1

    fig, ax = plt.subplots(figsize=(5, 3.2))
    colors = {"low": "#4caf50", "medium": "#ffb300", "high": "#e53935"}
    bands = ["low", "medium", "high"]
    ax.bar(bands, [band_counts[b] for b in bands], color=[colors[b] for b in bands])
    ax.set_ylabel("Patients")
    ax.set_title("Risk band distribution")
    fig.tight_layout()

    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110)
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def write_csv(rows: list[dict], path: str) -> None:
    fieldnames = [
        "patient_id",
        "name",
        "ward",
        "bed",
        "vitals_score",
        "vitals_band",
        "abnormal_test_count",
        "abnormal_labs",
        "adjusted_risk_score",
        "risk_band",
        "score_delta",
        "delta_direction",
        "reason_codes",
    ]
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for r in rows:
            writer.writerow({k: r.get(k) for k in fieldnames})


def build_report(sim_day: str, dsn: str, reports_dir: str, logger) -> tuple[str, str]:
    rows, alerts, spikes = fetch_report_data(dsn, sim_day)
    chart_b64 = build_ward_chart(rows) if rows else ""

    html = Template(REPORT_TEMPLATE).render(
        sim_day=sim_day, rows=rows, alerts=alerts, spikes=spikes, chart_b64=chart_b64
    )

    os.makedirs(reports_dir, exist_ok=True)
    html_path = os.path.join(reports_dir, f"daily_risk_report_{sim_day}.html")
    csv_path = os.path.join(reports_dir, f"daily_risk_report_{sim_day}.csv")

    with open(html_path, "w", encoding="utf-8") as fh:
        fh.write(html)
    write_csv(rows, csv_path)

    logger.info("report_built", stage="serving", sim_day=sim_day, patients=len(rows), html_path=html_path)
    return html_path, csv_path


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--sim-day", required=True)
    args = parser.parse_args()

    settings = get_settings()
    logger = configure_logging("report-builder", logs_dir=os.environ.get("LOGS_DIR"))
    reports_dir = os.environ.get("REPORTS_DIR", settings.reports_dir)

    build_report(args.sim_day, settings.postgres_dsn_vitals, reports_dir, logger)


if __name__ == "__main__":
    main()
